#!/usr/bin/env node
// Generates packages/ui/src/symbols/data.ts — the character names of the symbol picker —
// from the Unicode Character Database (UnicodeData.txt + Blocks.txt, Unicode License v3).
//
//   node scripts/gen-symbols.mjs [--ucd <dir with UnicodeData.txt and Blocks.txt>]
//
// Without --ucd the two files are downloaded from unicode.org (pinned version below) into a
// temporary folder. Only the subset of blocks listed in BLOCKS is written, and names are
// compressed with a shared word table so the bundle stays small.
import { mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const UCD_VERSION = '16.0.0';
const BASE = `https://www.unicode.org/Public/${UCD_VERSION}/ucd`;

/** Blocks offered in the picker: stable id → UCD block name (optionally a narrower range). */
const BLOCKS = [
  { id: 'basicLatin', block: 'Basic Latin', start: 0x20, end: 0x7e },
  { id: 'latin1', block: 'Latin-1 Supplement', start: 0xa0 },
  { id: 'latinExtA', block: 'Latin Extended-A' },
  { id: 'latinExtB', block: 'Latin Extended-B' },
  { id: 'latinExtAdditional', block: 'Latin Extended Additional' },
  { id: 'spacingModifiers', block: 'Spacing Modifier Letters' },
  { id: 'greek', block: 'Greek and Coptic' },
  { id: 'cyrillic', block: 'Cyrillic' },
  { id: 'generalPunctuation', block: 'General Punctuation' },
  { id: 'superSub', block: 'Superscripts and Subscripts' },
  { id: 'currency', block: 'Currency Symbols' },
  { id: 'letterlike', block: 'Letterlike Symbols' },
  { id: 'numberForms', block: 'Number Forms' },
  { id: 'arrows', block: 'Arrows' },
  { id: 'mathOperators', block: 'Mathematical Operators' },
  { id: 'miscTechnical', block: 'Miscellaneous Technical' },
  { id: 'enclosedAlphanumerics', block: 'Enclosed Alphanumerics' },
  { id: 'boxDrawing', block: 'Box Drawing' },
  { id: 'blockElements', block: 'Block Elements' },
  { id: 'geometricShapes', block: 'Geometric Shapes' },
  { id: 'miscSymbols', block: 'Miscellaneous Symbols' },
  { id: 'dingbats', block: 'Dingbats' },
  { id: 'supArrowsA', block: 'Supplemental Arrows-A' },
  { id: 'supArrowsB', block: 'Supplemental Arrows-B' },
  { id: 'miscSymbolsArrows', block: 'Miscellaneous Symbols and Arrows' },
];

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'packages/ui/src/symbols/data.ts');

async function ucdDir() {
  const i = process.argv.indexOf('--ucd');
  if (i > 0 && process.argv[i + 1]) return process.argv[i + 1];
  const dir = await mkdtemp(join(tmpdir(), 'bo-ucd-'));
  for (const f of ['UnicodeData.txt', 'Blocks.txt']) {
    const res = await fetch(`${BASE}/${f}`);
    if (!res.ok) throw new Error(`${f}: HTTP ${res.status}`);
    await writeFile(join(dir, f), await res.text());
  }
  return dir;
}

const dir = await ucdDir();
const blocksTxt = await readFile(join(dir, 'Blocks.txt'), 'utf8');
const dataTxt = await readFile(join(dir, 'UnicodeData.txt'), 'utf8');

const ranges = new Map();
for (const line of blocksTxt.split('\n')) {
  const m = /^([0-9A-F]+)\.\.([0-9A-F]+);\s*(.+?)\s*$/.exec(line);
  if (m) ranges.set(m[3], [parseInt(m[1], 16), parseInt(m[2], 16)]);
}

const names = new Map();
for (const line of dataTxt.split('\n')) {
  const f = line.split(';');
  if (f.length < 3 || f[1].startsWith('<')) continue; // controls, ranges, private use
  if (f[2].startsWith('M')) continue; // combining marks do not stand alone in a grid
  names.set(parseInt(f[0], 16), f[1]);
}

// Word table, most frequent first (shortest indexes).
const freq = new Map();
const picked = BLOCKS.map((b) => {
  const r = ranges.get(b.block);
  if (!r) throw new Error(`unknown block ${b.block}`);
  const start = b.start ?? r[0];
  const end = b.end ?? r[1];
  const list = [];
  for (let cp = start; cp <= end; cp++) {
    const n = names.get(cp) ?? '';
    list.push(n);
    for (const w of n.split(' ').filter(Boolean)) freq.set(w, (freq.get(w) ?? 0) + 1);
  }
  return { ...b, start, end, list };
});
const words = [...freq.entries()]
  .sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))
  .map((e) => e[0]);
const index = new Map(words.map((w, i) => [w, i.toString(36)]));

const lines = [
  `// Generated by scripts/gen-symbols.mjs from the Unicode Character Database ${UCD_VERSION}`,
  '// (UnicodeData.txt, Blocks.txt; © Unicode, Inc., Unicode License v3). Do not edit.',
  '//',
  '// WORDS: name words, space separated. Each block lists one entry per code point',
  "// from `start` to `end`, separated by '|': base-36 word indexes joined by '.',",
  '// empty for code points without a picker entry (unassigned, controls, marks).',
  '',
  `export const UCD_VERSION = '${UCD_VERSION}';`,
  '',
  'export const WORDS =',
  `  '${words.join(' ')}';`,
  '',
  'export interface RawBlock {',
  '  id: string;',
  '  /** Block name in the UCD (English). */',
  '  name: string;',
  '  start: number;',
  '  end: number;',
  '  names: string;',
  '}',
  '',
  'export const BLOCKS: readonly RawBlock[] = [',
];
let count = 0;
for (const b of picked) {
  const enc = b.list.map((n) =>
    n
      .split(' ')
      .filter(Boolean)
      .map((w) => index.get(w))
      .join('.'),
  );
  count += b.list.filter(Boolean).length;
  const hex = (n) => `0x${n.toString(16).padStart(4, '0')}`;
  lines.push('  {');
  lines.push(`    id: '${b.id}',`);
  lines.push(`    name: '${b.block}',`);
  lines.push(`    start: ${hex(b.start)},`);
  lines.push(`    end: ${hex(b.end)},`);
  lines.push('    names:', `      '${enc.join('|')}',`);
  lines.push('  },');
}
lines.push('];', '');
await writeFile(out, lines.join('\n'));
console.log(`${out}: ${picked.length} blocks, ${count} characters, ${words.length} words`);
