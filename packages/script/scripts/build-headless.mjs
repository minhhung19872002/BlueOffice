// Builds the headless BlueScript bundle (CORE-SCRIPT-004): the API hosts, the
// prelude and the wrapper of packages/script as one plain-JavaScript IIFE that
// the native runtime (crates/bo-script) embeds with `include_str!`.
//
//   node packages/script/scripts/build-headless.mjs          # write the bundle
//   node packages/script/scripts/build-headless.mjs --check  # fail if it is stale
//
// `test/headless.test.ts` runs the check too, so the Rust copy cannot drift from
// the TypeScript sources.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, '..');
export const BUNDLE = join(pkg, '..', '..', 'crates', 'bo-script', 'js', 'bluescript-headless.js');

const HEADER =
  '// GENERATED by packages/script/scripts/build-headless.mjs from packages/script/src\n' +
  '// (headless-entry.ts). Do not edit: run `node packages/script/scripts/build-headless.mjs`.\n';

/** The bundle source. */
export async function bundle() {
  const out = await build({
    configFile: false,
    root: pkg,
    logLevel: 'silent',
    build: {
      write: false,
      minify: false,
      sourcemap: false,
      target: 'es2022',
      lib: {
        entry: join(pkg, 'src', 'headless-entry.ts'),
        formats: ['iife'],
        name: 'BlueScriptHeadless',
        fileName: () => 'bluescript-headless.js',
      },
    },
  });
  const outputs = (Array.isArray(out) ? out : [out]).flatMap((o) => o.output ?? []);
  const chunk = outputs.find((o) => o.type === 'chunk');
  if (!chunk) throw new Error('no bundle produced');
  return HEADER + chunk.code.replace(/\r\n/g, '\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const code = await bundle();
  if (process.argv.includes('--check')) {
    const current = readFileSync(BUNDLE, 'utf8').replace(/\r\n/g, '\n');
    if (current !== code) {
      console.error(`${BUNDLE} is stale: run node packages/script/scripts/build-headless.mjs`);
      process.exit(1);
    }
  } else {
    writeFileSync(BUNDLE, code);
    console.log(`wrote ${BUNDLE} (${code.length} bytes)`);
  }
}
