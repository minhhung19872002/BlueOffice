/// Additional value, edge and error rows for the Financial list (gap #37);
/// the expected values solve the annuity equation by hand.
#[test]
fn financial_edge_cases() {
    check(
        &[],
        &[
            (
                "=PMT(0.1,1,-100)",
                Near(110.0, TOL),
                "hand: one period, 100·1.1",
            ),
            (
                "=PMT(\"x\",1,1)",
                E("#VALUE!"),
                "ECMA-376 §18.17.7 PMT; hand: non-numeric rate",
            ),
            (
                "=IPMT(0,1,10,1000)",
                N(0.0),
                "hand: zero rate → no interest",
            ),
            ("=IPMT(0.1,1,1,100)", Near(-10.0, TOL), "hand: 100·0.1"),
            (
                "=IPMT(0.1,0,3,8000)",
                E("#NUM!"),
                "ECMA-376 §18.17.7 IPMT; hand: per < 1",
            ),
            ("=PPMT(0,1,10,1000)", N(-100.0), "hand: zero rate → 1000/10"),
            (
                "=PPMT(0.1,1,1,100)",
                Near(-100.0, TOL),
                "hand: payment 110 minus interest 10",
            ),
            (
                "=PPMT(0.1,11,10,1000)",
                E("#NUM!"),
                "ECMA-376 §18.17.7 PPMT; hand: per > nper",
            ),
            ("=PV(0.1,1,0,-110)", Near(100.0, TOL), "hand: 110/1.1"),
            (
                "=PV(0.05,2,-100,0,1)",
                Near(195.238_095_238_095, TOL),
                "hand: 100·1.05·(1.05²-1)/0.05 / 1.05² = 215.25/1.1025",
            ),
            (
                "=PV(\"x\",1,1)",
                E("#VALUE!"),
                "ECMA-376 §18.17.7 PV; hand: non-numeric rate",
            ),
            ("=FV(0.1,1,0,-100)", Near(110.0, TOL), "hand: 100·1.1"),
            ("=FV(0.1,2,-100)", Near(210.0, TOL), "hand: 100·1.1 + 100"),
            ("=NPV(0,1,2,3)", N(6.0), "hand: zero rate → plain sum"),
            ("=NPV(0.1,110)", Near(100.0, TOL), "hand: 110/1.1"),
            (
                "=NPV(-1,1)",
                E("#DIV/0!"),
                "ECMA-376 §18.17.7 NPV; hand: 1+rate = 0",
            ),
            (
                "=XNPV(0,{-100,50,60},{39448,39813,40178})",
                N(10.0),
                "hand: zero rate → plain sum",
            ),
            (
                "=XNPV(0.1,{-100,110},{39448,39813})",
                Near(0.0, TOL),
                "hand: 365 days later 110/1.1 = 100",
            ),
            (
                "=XNPV(0.1,{-100,\"a\"},{39448,39813})",
                E("#VALUE!"),
                "ECMA-376 §18.17.7 XNPV; hand: non-numeric value",
            ),
            (
                "=XIRR({-100,110},{39448,39813})",
                Near(0.1, 1e-8),
                "hand: 110 one 365-day year after -100",
            ),
            (
                "=XIRR({100,110},{39448,39813})",
                E("#NUM!"),
                "ECMA-376 §18.17.7 XIRR; hand: no sign change",
            ),
            ("=IRR({-100,110})", Near(0.1, 1e-8), "hand: 110/100 - 1"),
            ("=RATE(1,0,-100,110)", Near(0.1, 1e-9), "hand: 110/100 - 1"),
            ("=RATE(2,0,-100,121)", Near(0.1, 1e-9), "hand: √1.21 - 1"),
            (
                "=RATE(10,0,100,100)",
                E("#NUM!"),
                "ECMA-376 §18.17.7 RATE; hand: no solution (same signs)",
            ),
            ("=NPER(0,-100,1000)", N(10.0), "hand: zero rate → 1000/100"),
            (
                "=NPER(0.1,0,100,-110)",
                Near(1.0, 1e-12),
                "hand: ln(1.1)/ln(1.1)",
            ),
            (
                "=NPER(0,0,100)",
                E("#NUM!"),
                "ECMA-376 §18.17.7 NPER; hand: zero rate and payment",
            ),
            ("=SLN(1000,100,3)", N(300.0), "hand: (1000-100)/3"),
            (
                "=SLN(\"x\",1,1)",
                E("#VALUE!"),
                "ECMA-376 §18.17.7 SLN; hand: non-numeric cost",
            ),
            (
                "=DB(1000,100,5,1)",
                Near(369.0, TOL),
                "hand: rate 1-(0.1)^(1/5) = 0.369 (3 dp), 1000·0.369",
            ),
            (
                "=DB(1000,100,0,1)",
                E("#NUM!"),
                "ECMA-376 §18.17.7 DB; hand: life ≤ 0",
            ),
            ("=DDB(1000,100,5,1)", Near(400.0, TOL), "hand: 1000·2/5"),
            (
                "=DDB(1000,100,5,6)",
                E("#NUM!"),
                "ECMA-376 §18.17.7 DDB; hand: period > life",
            ),
        ],
    );
}
