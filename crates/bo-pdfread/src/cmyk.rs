/// CMYK in 0..=1 to RGB in 0..=1.
pub(crate) fn cmyk_to_rgb(c: f32, m: f32, y: f32, k: f32) -> [f32; 3] {
    let split = |v: f32| {
        let t = v.clamp(0.0, 1.0) * 4.0;
        let i = (t.floor() as usize).min(3);
        (i, t - i as f32)
    };
    let (ci, cf) = split(c);
    let (mi, mf) = split(m);
    let (yi, yf) = split(y);
    let (ki, kf) = split(k);
    let mut out = [0.0_f32; 3];
    for bits in 0..16_usize {
        let pick = |b: usize, i: usize, f: f32| {
            if bits >> b & 1 == 1 {
                (i + 1, f)
            } else {
                (i, 1.0 - f)
            }
        };
        let (c1, wc) = pick(0, ci, cf);
        let (m1, wm) = pick(1, mi, mf);
        let (y1, wy) = pick(2, yi, yf);
        let (k1, wk) = pick(3, ki, kf);
        let w = wc * wm * wy * wk;
        if w == 0.0 {
            continue;
        }
        let px = LUT[((c1 * 5 + m1) * 5 + y1) * 5 + k1];
        for (o, v) in out.iter_mut().zip(px) {
            *o += w * f32::from(v) / 255.0;
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::cmyk_to_rgb;

    #[test]
    fn measured_process_colours() {
        let px = |c, m, y, k| cmyk_to_rgb(c, m, y, k).map(|v| (v * 255.0).round() as u8);
        assert_eq!(px(0.0, 0.0, 0.0, 0.0), [255, 255, 255]);
        assert_eq!(px(1.0, 0.0, 0.0, 0.0), [0, 173, 238]);
        assert_eq!(px(0.0, 0.0, 0.0, 1.0), [36, 32, 33]);
        // Between the patches the values blend.
        let h = px(0.125, 0.0, 0.0, 0.0);
        assert!(h[0] < 255 && h[0] > 180, "{h:?}");
    }
}
