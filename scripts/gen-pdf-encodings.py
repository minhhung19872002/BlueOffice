"""Generate crates/bo-pdfread/src/encoding_data.rs from lopdf 0.38 (MIT) tables:
the PDF base encodings (ISO 32000-1 Annex D) as glyph names and the Adobe Glyph List."""
import glob
import os
import re
import sys

root = glob.glob(os.path.expanduser('~/.cargo/registry/src/*/lopdf-0.38.0'))[0]
names = open(os.path.join(root, 'src/encodings/glyphnames.rs'), encoding='utf-8').read()
agl = re.findall(r'pub const (\w+): u16 = 0x([0-9a-fA-F]+);', names)
maps = open(os.path.join(root, 'src/encodings/mappings.rs'), encoding='utf-8').read()

out = []
out.append('//! Generated by `scripts/gen-pdf-encodings.py`: PDF base encodings as glyph names (ISO 32000-1,')
out.append('//! Annex D) and the Adobe Glyph List (glyph name to Unicode), from lopdf 0.38 (MIT).')
out.append('')
for const, rust in [('STANDARD', 'STANDARD_ENCODING'), ('WIN_ANSI', 'WIN_ANSI_ENCODING'),
                    ('MAC_ROMAN', 'MAC_ROMAN_ENCODING'), ('SYMBOL', 'SYMBOL_ENCODING'),
                    ('MAC_EXPERT', 'MAC_EXPERT_ENCODING')]:
    m = re.search(r'pub const ' + rust + r': CodedCharacterSet = \[(.*?)\];', maps, re.S)
    items = [i.strip() for i in m.group(1).split(',') if i.strip()]
    assert len(items) == 256, (rust, len(items))
    vals = []
    for i in items:
        g = re.match(r'Some\(Glyph::(\w+)\)', i)
        vals.append('"%s"' % g.group(1) if g else '""')
    out.append('/// %s as glyph names (`""`: no glyph).' % rust)
    out.append('pub(crate) const %s: [&str; 256] = [' % const)
    for k in range(0, 256, 8):
        out.append('    ' + ', '.join(vals[k:k + 8]) + ',')
    out.append('];')
    out.append('')
agl.sort(key=lambda p: p[0].encode())
out.append('/// Adobe Glyph List: glyph name to UTF-16 code unit, sorted by name.')
out.append('pub(crate) const AGL: [(&str, u16); %d] = [' % len(agl))
for n, v in agl:
    out.append('    ("%s", 0x%s),' % (n, v.lower()))
out.append('];')
open(sys.argv[1], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(len(agl))
