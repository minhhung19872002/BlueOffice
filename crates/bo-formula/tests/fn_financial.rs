//! Financial functions.
//!
//! Sources: ECMA-376 Part 1, §18.17.7 (PMT, IPMT, PPMT, PV, FV, NPV, XNPV, IRR,
//! XIRR, RATE, NPER, SLN, SYD, DB, DDB, EFFECT, NOMINAL, CUMIPMT, CUMPRINC) and
//! OpenFormula (ODF 1.3 Part 4) Financial functions, which define the annuity
//! equation  pv·(1+r)^n + pmt·(1+r·type)·((1+r)^n − 1)/r + fv = 0.
//! Expected values are the published worked examples, re-derived from that
//! equation (and the DB/DDB depreciation definitions) to full precision.

mod common;
use common::*;

const TOL: f64 = 1e-6;

